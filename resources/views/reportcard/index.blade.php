@extends('layouts.app')

@section('content')
<div class="container mx-auto py-8 px-4">
    <h1 class="text-3xl font-bold text-gray-900 mb-8">My Report Cards</h1>

    @if($reportCards->isEmpty())
        <div class="bg-gray-50 border border-gray-200 rounded-lg p-12 text-center">
            <i class="fas fa-file-pdf text-5xl text-gray-400 mb-4"></i>
            <p class="text-lg text-gray-600">No report cards available yet.</p>
            <p class="text-sm text-gray-500 mt-2">Report cards will appear here once they are generated by the school.</p>
        </div>
    @else
        <div class="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
            @foreach($reportCards as $reportCard)
                @php
                    // Get settings for this specific report card
                    $settings = \App\Models\ReportCardSetting::where('is_active', true)
                        ->where('academic_year', $reportCard->academicYear->year ?? '')
                        ->where('term', $reportCard->term->name ?? '')
                        ->first();
                    
                    $now = \Carbon\Carbon::now();
                    $releaseAt = $settings && $settings->report_card_available_at 
                        ? \Carbon\Carbon::parse($settings->report_card_available_at) 
                        : null;
                    
                    $outstanding = auth('student')->user()->getOutstandingFees();
                    
                    // Determine status
                    if ($outstanding > 0) {
                        $status = 'blocked_fees';
                        $statusText = 'Payment Required';
                        $badgeColor = 'red';
                    } elseif ($releaseAt && $now->lt($releaseAt)) {
                        $status = 'countdown';
                        $statusText = 'Coming Soon';
                        $badgeColor = 'yellow';
                    } else {
                        $status = 'accessible';
                        $statusText = 'Available';
                        $badgeColor = 'green';
                    }
                @endphp

                <div class="bg-white border-2 rounded-lg shadow-md overflow-hidden hover:shadow-lg transition duration-300
                    @if($badgeColor === 'red') border-red-300
                    @elseif($badgeColor === 'yellow') border-yellow-300
                    @else border-green-300
                    @endif
                ">
                    <!-- Header -->
                    <div class="p-4 @if($badgeColor === 'red') bg-red-50
                        @elseif($badgeColor === 'yellow') bg-yellow-50
                        @else bg-green-50
                        @endif
                    ">
                        <div class="flex items-center justify-between mb-2">
                            <h3 class="text-lg font-semibold text-gray-900">{{ $reportCard->course->name ?? 'N/A' }}</h3>
                            <span class="inline-block px-3 py-1 rounded-full text-xs font-bold
                                @if($badgeColor === 'red') bg-red-200 text-red-800
                                @elseif($badgeColor === 'yellow') bg-yellow-200 text-yellow-800
                                @else bg-green-200 text-green-800
                                @endif
                            ">
                                {{ $statusText }}
                            </span>
                        </div>
                        <p class="text-sm text-gray-600">{{ $reportCard->academicYear->year ?? 'N/A' }} - {{ $reportCard->term->name ?? 'N/A' }}</p>
                    </div>

                    <!-- Content -->
                    <div class="p-4">
                        <div class="mb-4">
                            <p class="text-sm text-gray-600 mb-1">Academic Year</p>
                            <p class="font-semibold text-gray-900">{{ $reportCard->academicYear->year ?? 'N/A' }}</p>
                        </div>

                        <div class="mb-4">
                            <p class="text-sm text-gray-600 mb-1">Term</p>
                            <p class="font-semibold text-gray-900">{{ $reportCard->term->name ?? 'N/A' }}</p>
                        </div>

                        <!-- Status Message -->
                        <div class="mb-4 p-3 rounded-lg
                            @if($badgeColor === 'red') bg-red-100 border border-red-300
                            @elseif($badgeColor === 'yellow') bg-yellow-100 border border-yellow-300
                            @else bg-green-100 border border-green-300
                            @endif
                        ">
                            @if($status === 'blocked_fees')
                                <p class="text-sm text-red-800">
                                    <strong>Outstanding Fees:</strong> RWF {{ number_format($outstanding, 2) }}
                                </p>
                            @elseif($status === 'countdown' && $releaseAt)
                                <p class="text-sm text-yellow-800">
                                    <strong>Available:</strong> {{ $releaseAt->diffForHumans() }}
                                </p>
                            @else
                                <p class="text-sm text-green-800">
                                    Available to download <i class="fas fa-check-circle"></i>
                                </p>
                            @endif
                        </div>

                        <!-- Action -->
                        <div class="flex gap-2">
                            @if($status === 'blocked_fees')
                                <button 
                                    class="flex-1 bg-red-600 hover:bg-red-700 text-white font-semibold py-2 px-3 rounded transition duration-300 text-sm flex items-center justify-center gap-2"
                                    onclick="window.location.href='{{ route('student.report-cards.show', $reportCard->id) }}'"
                                >
                                    <i class="fas fa-dollar-sign"></i>
                                    Pay & View
                                </button>
                            @elseif($status === 'countdown')
                                <button 
                                    class="flex-1 bg-yellow-600 hover:bg-yellow-700 text-white font-semibold py-2 px-3 rounded transition duration-300 text-sm flex items-center justify-center gap-2"
                                    onclick="window.location.href='{{ route('student.report-cards.show', $reportCard->id) }}'"
                                >
                                    <i class="fas fa-hourglass-half"></i>
                                    View Status
                                </button>
                            @else
                                <button 
                                    class="flex-1 bg-green-600 hover:bg-green-700 text-white font-semibold py-2 px-3 rounded transition duration-300 text-sm flex items-center justify-center gap-2"
                                    onclick="window.location.href='{{ route('student.report-cards.show', $reportCard->id) }}'"
                                >
                                    <i class="fas fa-eye"></i>
                                    View Report
                                </button>
                            @endif
                        </div>
                    </div>

                    <!-- Footer -->
                    <div class="px-4 py-3 bg-gray-50 text-xs text-gray-500 border-t">
                        Generated: {{ $reportCard->created_at->format('M d, Y H:i A') }}
                    </div>
                </div>
            @endforeach
        </div>
    @endif
</div>

